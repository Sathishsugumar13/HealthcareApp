export const getTabletPrice = (tablet: string): number => {
  if (!tablet) return 50;
  const clean = tablet.replace(/\(.*?\)/g, '').replace(/-\s*\d+.*$/, '').trim();
  const t = clean.toLowerCase();
  if (t === 'paracetamol (500mg)' || t === 'paracetamol') return 20;
  if (t === 'dolo 650' || t === 'dolo') return 25;
  if (t === 'amoxicillin') return 55;
  if (t === 'cetirizine') return 20;
  if (t === 'azithromycin') return 50;
  if (t === 'crocin' || t === 'crocine') return 35;
  if (t === 'aspirin') return 15;
  if (t === 'vitamin c') return 25;
  if (t === 'zincovit') return 65;
  if (t === 'pantoprazole') return 30;
  if (t === 'ibuprofen') return 20;
  if (t === 'metformin') return 15;
  if (t === 'amlodipine') return 20;
  if (t === 'omeprazole') return 10;
  if (t === 'atorvastatin') return 40;
  if (t === 'diclofenac') return 30;
  if (t === 'tramadol') return 40;
  if (t === 'ambroxol') return 35;
  if (t === 'b-complex' || t === 'b complex') return 15;
  if (t === 'liv52' || t === 'liv25' || t === 'liv 52') return 190;
  if (t === 'azel' || t === 'azel 160') return 25;
  if (t === 'augmentin' || t === 'augmentin 375') return 180;
  if (t === 'allegra' || t === 'allegra 120') return 230;
  if (t === 'becosules') return 60;
  if (t === 'montek lc' || t === 'montair lc') return 400;
  if (t === 'zifi 200' || t === 'zifi') return 100;
  if (t === 'shelcal 500' || t === 'shelcal') return 140;
  if (t === 'pan d' || t === 'pen d') return 55;
  if (t === 'thyronorm') return 200;
  return 120 + (tablet.length * 10);
};
